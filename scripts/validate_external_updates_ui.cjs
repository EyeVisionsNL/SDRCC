"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.join(root, "dashboard/templates/index.html"), "utf8");
const js = fs.readFileSync(path.join(root, "dashboard/static/js/external_updates.js"), "utf8");
const app = fs.readFileSync(path.join(root, "dashboard/app.py"), "utf8");
const installer = fs.readFileSync(path.join(root, "install.sh"), "utf8");
const updater = fs.readFileSync(path.join(root, "scripts/sdrcc_update.py"), "utf8");
const inventory = fs.readFileSync(path.join(root, "core/external_updates.py"), "utf8");
assert(html.includes("External Software · Versions"));
assert(html.includes('id="external-update-list"'));
assert(html.includes('id="external-update-check"'));
assert(!html.includes("External Software Updates"));
assert(js.includes('fetch("/api/external-updates"'));
assert(js.includes("INSTALLED") && js.includes("VERSION UNKNOWN"));
assert(!js.includes("/api/external-updates/install"));
assert(!js.includes("setInterval(") && !js.includes("can_install"));
assert(!app.includes('@app.route("/api/external-updates/install"'));
assert(!app.includes("EXTERNAL_UPDATE_HELPER"));
assert(!installer.includes("scripts/sdrcc_external_update.py"));
assert(!installer.includes('cat >"$tmp/sdrcc-external-update"'));
assert(!updater.includes('"scripts/sdrcc_external_update.py"'));
assert(!inventory.includes("urlopen(") && !inventory.includes("apt-get"));
console.log("PASS: external versions read-only; standalone updater retired.");
